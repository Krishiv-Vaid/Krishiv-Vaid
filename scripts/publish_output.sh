#!/usr/bin/env bash
# Publish generated assets to the `output` branch as a single orphan commit.
#
#   scripts/publish_output.sh <out-dir> <previous-dir> [branch]
#
# * Nothing is pushed when the assets are identical to what is already
#   published (snapshot.json is ignored for the comparison: it carries a
#   timestamp and is only a fallback cache).
# * The branch is force-pushed as one commit, so daily binary churn never
#   accumulates in the repository history and `main` stays free of bot commits.
set -euo pipefail

OUT=${1:?out dir}
PREV=${2:?previous dir}
BRANCH=${3:-output}

if [ -d "$PREV" ] && [ -n "$(ls -A "$PREV" 2>/dev/null)" ] \
   && diff -rq --exclude=snapshot.json --exclude=README.md --exclude=.git "$OUT" "$PREV" >/dev/null; then
  echo "assets unchanged; nothing to publish"
  exit 0
fi

cat > "$OUT/README.md" <<'MD'
# output

Generated by `.github/workflows/update-profile.yml` from the `main` branch.
This branch is force-pushed as a single commit on every change; do not edit it.
MD

cd "$OUT"
rm -rf .git
git init -q
git checkout -q --orphan "$BRANCH"
git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
git add -A
git commit -q -m "Regenerate profile assets ($(date -u +%Y-%m-%d))"
git push -q -f "https://x-access-token:${GITHUB_TOKEN}@github.com/${GITHUB_REPOSITORY}.git" "$BRANCH:$BRANCH"
echo "published to $BRANCH"
